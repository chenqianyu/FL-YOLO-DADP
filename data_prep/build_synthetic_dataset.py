#!/usr/bin/env python3
"""Assemble the fully synthetic YOLO training set for one generative model.

The "Generate" cell of each notebook in generative_models/ writes, for every
agent k, a folder ``<raw>/agent_<k>_synthesized/{train,valid}/{images,labels}``
holding agent k's frames re-generated by the model *plus the other agents' real
frames* (the partially-synthetic setting). This script keeps only the
synthesized frames, i.e. from ``agent_<k>_synthesized`` the frames that belong
to agent k, and merges them into one dataset:

    <out>/{train,valid}/{images,labels}, <out>/data.yaml     (7200 / 720 frames)

    python data_prep/build_synthetic_dataset.py --raw data/synthetic_raw/GANs \
        --agents data/agents --out data/synthetic/GANs
"""

import argparse
import os
import shutil

CLASS_NAMES = ["RBC", "WBC", "PLT"]


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--raw", required=True, help="folder with agent_<k>_synthesized sub-folders")
    p.add_argument("--agents", default="data/agents", help="real per-agent shards (to look up ownership)")
    p.add_argument("--out", required=True)
    p.add_argument("--num-agents", type=int, default=3)
    a = p.parse_args()

    for split in ("train", "valid"):
        os.makedirs(os.path.join(a.out, split, "images"), exist_ok=True)
        os.makedirs(os.path.join(a.out, split, "labels"), exist_ok=True)
        n = 0
        for k in range(a.num_agents):
            src = os.path.join(a.raw, f"agent_{k}_synthesized", split)
            own = set(os.listdir(os.path.join(a.agents, f"agent_{k}", split, "images")))
            for img in sorted(os.listdir(os.path.join(src, "images"))):
                if not img.endswith(".png") or img not in own:
                    continue
                shutil.copy(os.path.join(src, "images", img), os.path.join(a.out, split, "images", img))
                lbl = img[:-4] + ".txt"
                if os.path.isfile(os.path.join(src, "labels", lbl)):
                    shutil.copy(os.path.join(src, "labels", lbl), os.path.join(a.out, split, "labels", lbl))
                n += 1
        print(f"{split}: {n} synthesized frames")

    with open(os.path.join(a.out, "data.yaml"), "w") as f:
        f.write(
            f"path: {os.path.abspath(a.out)}\ntrain: train/images\nval: valid/images\n\n"
            f"nc: {len(CLASS_NAMES)}\nnames: {CLASS_NAMES}\n"
        )
    print(f"wrote {os.path.join(a.out, 'data.yaml')}")


if __name__ == "__main__":
    main()
